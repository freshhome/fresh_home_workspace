-- 1. CREATE GOVERNORATES REFERENCE TABLE
CREATE TABLE IF NOT EXISTS public.governorates (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_ar TEXT NOT NULL,
    name_en TEXT NOT NULL,
    code TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT true,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_governorates_code UNIQUE (code),
    CONSTRAINT uq_governorates_name_ar UNIQUE (name_ar),
    CONSTRAINT uq_governorates_name_en UNIQUE (name_en)
);

-- 2. CREATE CITIES REFERENCE TABLE WITH COMPOSITE UNIQUE KEY FOR HIERARCHY
CREATE TABLE IF NOT EXISTS public.cities (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    governorate_id INT NOT NULL REFERENCES public.governorates(id) ON DELETE RESTRICT,
    name_ar TEXT NOT NULL,
    name_en TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT true,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_cities_governorate_name_ar UNIQUE (governorate_id, name_ar),
    CONSTRAINT uq_cities_governorate_name_en UNIQUE (governorate_id, name_en),
    CONSTRAINT uq_cities_id_governorate_id UNIQUE (id, governorate_id)
);

-- 3. CREATE DISTRICTS REFERENCE TABLE WITH COMPOSITE UNIQUE KEY FOR HIERARCHY
CREATE TABLE IF NOT EXISTS public.districts (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id INT NOT NULL REFERENCES public.cities(id) ON DELETE RESTRICT,
