    CONSTRAINT uq_districts_city_name_ar UNIQUE (city_id, name_ar),
    CONSTRAINT uq_districts_city_name_en UNIQUE (city_id, name_en),
    CONSTRAINT uq_districts_id_city_id UNIQUE (id, city_id)
);

