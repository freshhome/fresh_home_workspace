  /// Returns districts list for a given governorate and city name.
  static List<String> getDistricts(String? governorate, String? city) {
    if (governorate == null || city == null) return const [];
    final cleanGov = governorate.trim();
    final cleanCity = city.trim();

    for (final govEntry in hierarchy.entries) {
      if (govEntry.key == cleanGov ||
          cleanGov.contains(govEntry.key) ||
          govEntry.key.contains(cleanGov)) {
        for (final cityEntry in govEntry.value.entries) {
          if (cityEntry.key == cleanCity ||
              cleanCity.contains(cityEntry.key) ||
              cityEntry.key.contains(cleanCity)) {
            return cityEntry.value;
          }
        }
      }
    }
    return const [];
  }
